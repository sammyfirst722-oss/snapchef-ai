import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, '..')

// Read recipes-data.ts
const recipesDataPath = path.join(ROOT, 'lib', 'recipes-data.ts')
const content = fs.readFileSync(recipesDataPath, 'utf8')

// Extract the RECIPES_DATA JSON
const jsonStart = content.indexOf('export const RECIPES_DATA: Recipe[] = ')
if (jsonStart === -1) {
  console.error('Could not find RECIPES_DATA')
  process.exit(1)
}

const rawArray = content.slice(jsonStart + 'export const RECIPES_DATA: Recipe[] = '.length).trim()
const cleanJson = rawArray.endsWith(';') ? rawArray.slice(0, -1) : rawArray
const recipes = JSON.parse(cleanJson)

console.log(`Analyzing ${recipes.length} recipes for ingredient co-occurrence...`)

function slugifyKey(key) {
  return key
    .trim()
    .toLowerCase()
    .replace(/[\s_]+/g, '-')
    .replace(/[^a-z0-9-]/g, '')
}

function formatName(key) {
  return key
    .replace(/[\s_]+/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join(' ')
}

const pairMap = new Map()

for (const recipe of recipes) {
  const rawKeys = [...new Set(
    recipe.ingredients
      .map(i => i.standardKey?.trim().toLowerCase())
      .filter(Boolean)
  )]

  const slugified = [...new Set(rawKeys.map(k => slugifyKey(k)))].sort()

  for (let i = 0; i < slugified.length; i++) {
    for (let j = i + 1; j < slugified.length; j++) {
      const keyA = slugified[i]
      const keyB = slugified[j]
      const slug = `${keyA}-and-${keyB}`

      if (!pairMap.has(slug)) {
        pairMap.set(slug, {
          slug,
          keyA,
          keyB,
          nameA: formatName(keyA),
          nameB: formatName(keyB),
          title: `${formatName(keyA)} & ${formatName(keyB)}`,
          count: 0,
          recipeIds: []
        })
      }

      const entry = pairMap.get(slug)
      entry.count++
      if (!entry.recipeIds.includes(recipe.id)) {
        entry.recipeIds.push(recipe.id)
      }
    }
  }
}

// Enforce Claude's 5-recipe minimum threshold (anti-thin content rule)
const MIN_RECIPES = 5
const validPairs = Array.from(pairMap.values())
  .filter(p => p.count >= MIN_RECIPES)
  .sort((a, b) => b.count - a.count)

console.log(`Found ${pairMap.size} total ingredient pairs.`)
console.log(`Retained ${validPairs.length} high-quality pairs with >= ${MIN_RECIPES} recipes!`)

console.log('\nTop 15 most frequent pairs:')
validPairs.slice(0, 15).forEach((p, idx) => {
  console.log(`  ${idx + 1}. ${p.title} (${p.slug}): ${p.count} recipes`)
})

// Generate lib/ingredient-pairs-data.ts
const code = `// Auto-generated by scripts/generate-ingredient-pairs.mjs
// DO NOT EDIT DIRECTLY. Run 'node scripts/generate-ingredient-pairs.mjs' to regenerate.

export interface IngredientPair {
  slug: string
  keyA: string
  keyB: string
  nameA: string
  nameB: string
  title: string
  count: number
  recipeIds: string[]
}

export const INGREDIENT_PAIRS: IngredientPair[] = ${JSON.stringify(validPairs, null, 2)}

export const INGREDIENT_PAIRS_MAP: Record<string, IngredientPair> = Object.fromEntries(
  INGREDIENT_PAIRS.map(p => [p.slug, p])
)

export function getIngredientPairBySlug(slug: string): IngredientPair | undefined {
  return INGREDIENT_PAIRS_MAP[slug.toLowerCase().trim()]
}
`

const outPath = path.join(ROOT, 'lib', 'ingredient-pairs-data.ts')
fs.writeFileSync(outPath, code, 'utf8')
console.log(`\nWrote ${validPairs.length} pairs to ${outPath}`)
