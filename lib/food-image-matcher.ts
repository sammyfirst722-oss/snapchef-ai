function hashString(str: string): number {
  let hash = 0
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i)
    hash |= 0
  }
  return Math.abs(hash)
}

export function getMatchingFoodImage(recipe: {
  title: string
  category?: string
  ingredients?: any[]
  tags?: string[]
  id?: string
}): string {
  const title = (recipe.title || '').toLowerCase()
  const category = (recipe.category || '').toLowerCase()
  const tags = (recipe.tags || []).map((t) => t.toLowerCase()).join(' ')
  const ingredients = (recipe.ingredients || [])
    .map((i) => (typeof i === 'string' ? i : i.item || ''))
    .join(' ')
    .toLowerCase()
  const combined = `${title} ${category} ${tags} ${ingredients}`

  const seed = hashString(recipe.id || recipe.title || 'snapchef')

  // 1. Exact Title / Dish Matching (High Specificity)
  if (title.includes('quesadilla')) {
    return FOOD_ARCHETYPES.quesadilla[seed % FOOD_ARCHETYPES.quesadilla.length]
  }
  if (title.includes('french toast')) {
    return FOOD_ARCHETYPES.french_toast[seed % FOOD_ARCHETYPES.french_toast.length]
  }
  if (title.includes('pancake') || title.includes('waffle')) {
    return FOOD_ARCHETYPES.pancakes[seed % FOOD_ARCHETYPES.pancakes.length]
  }
  if (title.includes('grilled cheese')) {
    return FOOD_ARCHETYPES.grilled_cheese[seed % FOOD_ARCHETYPES.grilled_cheese.length]
  }
  if (
    title.includes('macaroni') ||
    title.includes('mac & cheese') ||
    title.includes('mac and cheese')
  ) {
    return FOOD_ARCHETYPES.mac_and_cheese[seed % FOOD_ARCHETYPES.mac_and_cheese.length]
  }
  if (
    title.includes('hash brown') ||
    title.includes('hashbrown') ||
    title.includes('skillet potato')
  ) {
    return FOOD_ARCHETYPES.hash_browns[seed % FOOD_ARCHETYPES.hash_browns.length]
  }
  if (title.includes('fried rice') || (title.includes('rice') && combined.includes('soy'))) {
    return FOOD_ARCHETYPES.fried_rice[seed % FOOD_ARCHETYPES.fried_rice.length]
  }
  if (title.includes('taco')) {
    return FOOD_ARCHETYPES.tacos[seed % FOOD_ARCHETYPES.tacos.length]
  }
  if (title.includes('scramble') || (title.includes('egg') && title.includes('cheddar'))) {
    return FOOD_ARCHETYPES.eggs_scramble[seed % FOOD_ARCHETYPES.eggs_scramble.length]
  }
  if (title.includes('fried egg') || (title.includes('egg') && title.includes('toast'))) {
    return FOOD_ARCHETYPES.eggs_fried_toast[seed % FOOD_ARCHETYPES.eggs_fried_toast.length]
  }
  if (title.includes('bacon')) {
    return FOOD_ARCHETYPES.bacon[seed % FOOD_ARCHETYPES.bacon.length]
  }
  if (title.includes('mushroom') && !title.includes('chicken') && !title.includes('beef')) {
    return FOOD_ARCHETYPES.mushrooms[seed % FOOD_ARCHETYPES.mushrooms.length]
  }
  if (title.includes('salmon')) {
    return FOOD_ARCHETYPES.salmon[seed % FOOD_ARCHETYPES.salmon.length]
  }
  if (title.includes('shrimp')) {
    return FOOD_ARCHETYPES.shrimp[seed % FOOD_ARCHETYPES.shrimp.length]
  }
  if (
    title.includes('steak') ||
    (title.includes('beef') && !title.includes('ground') && !title.includes('burger'))
  ) {
    return FOOD_ARCHETYPES.beef_steak[seed % FOOD_ARCHETYPES.beef_steak.length]
  }
  if (title.includes('burger')) {
    return FOOD_ARCHETYPES.burger[seed % FOOD_ARCHETYPES.burger.length]
  }
  if (title.includes('ground beef') || title.includes('chili')) {
    return FOOD_ARCHETYPES.beef_ground_chili[seed % FOOD_ARCHETYPES.beef_ground_chili.length]
  }
  if (title.includes('pizza')) {
    return FOOD_ARCHETYPES.pizza[seed % FOOD_ARCHETYPES.pizza.length]
  }
  if (title.includes('curry')) {
    return FOOD_ARCHETYPES.curry[seed % FOOD_ARCHETYPES.curry.length]
  }
  if (title.includes('soup') || title.includes('stew') || category.includes('soup')) {
    return FOOD_ARCHETYPES.soup[seed % FOOD_ARCHETYPES.soup.length]
  }
  if (title.includes('salad') || category.includes('salad')) {
    return FOOD_ARCHETYPES.salad[seed % FOOD_ARCHETYPES.salad.length]
  }
  if (
    title.includes('pasta') ||
    title.includes('spaghetti') ||
    title.includes('penne') ||
    category === 'pasta'
  ) {
    if (combined.includes('parmesan') || combined.includes('butter') || combined.includes('cream')) {
      return FOOD_ARCHETYPES.pasta_creamy[seed % FOOD_ARCHETYPES.pasta_creamy.length]
    }
    return FOOD_ARCHETYPES.pasta_tomato[seed % FOOD_ARCHETYPES.pasta_tomato.length]
  }
  if (title.includes('sandwich') || title.includes('wrap')) {
    return FOOD_ARCHETYPES.sandwich_wrap[seed % FOOD_ARCHETYPES.sandwich_wrap.length]
  }

  // 2. Chicken Preparation Styles
  if (combined.includes('chicken')) {
    if (
      title.includes('chipotle') ||
      title.includes('mexican') ||
      title.includes('lime') ||
      title.includes('fajita')
    ) {
      return FOOD_ARCHETYPES.chicken_chipotle[seed % FOOD_ARCHETYPES.chicken_chipotle.length]
    }
    if (
      title.includes('sesame') ||
      title.includes('ginger') ||
      title.includes('soy') ||
      title.includes('teriyaki')
    ) {
      return FOOD_ARCHETYPES.chicken_asian_sesame[
        seed % FOOD_ARCHETYPES.chicken_asian_sesame.length
      ]
    }
    if (title.includes('crispy') || title.includes('air fryer')) {
      return FOOD_ARCHETYPES.chicken_crispy_air_fryer[
        seed % FOOD_ARCHETYPES.chicken_crispy_air_fryer.length
      ]
    }
    if (title.includes('stir fry') || title.includes('stir-fry')) {
      return FOOD_ARCHETYPES.stir_fry[seed % FOOD_ARCHETYPES.stir_fry.length]
    }
    return FOOD_ARCHETYPES.chicken_roasted[seed % FOOD_ARCHETYPES.chicken_roasted.length]
  }

  // 3. Category Fallbacks
  if (category.includes('breakfast')) {
    return FOOD_ARCHETYPES.eggs_scramble[seed % FOOD_ARCHETYPES.eggs_scramble.length]
  }
  if (category.includes('fresh') || category.includes('healthy')) {
    return FOOD_ARCHETYPES.salad[seed % FOOD_ARCHETYPES.salad.length]
  }

  return FOOD_ARCHETYPES.chicken_roasted[seed % FOOD_ARCHETYPES.chicken_roasted.length]
}
